UNDERSTAND_SKILL_SOURCE = Path(__file__).parent.parent / "agents-understand"


def create_file(path: Path, content: str, dry_run: bool = False, force: bool = False) -> tuple[bool, bool]:
    """Write content to a file, creating parent directories as needed.
    Returns (written, existed) tuple."""
    existed = path.exists()
    if existed and not force:
        print(f"  ⚠  SKIP (exists): {path}")
        return (False, existed)
    if dry_run:
        action = "OVERWRITE" if existed else "CREATE"
        print(f"  ○  WOULD {action}: {path}")
        return (True, existed)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    action = "OVERWRITTEN" if existed else "CREATED"
    print(f"  ✓  {action}: {path}")
    return (True, existed)


def customize_content(content: str, project_name: str) -> str:
    """Replace placeholders in template content."""
    return content.replace("{project_name}", project_name)


def init_repo(target_dir: Path, project_name: str, dry_run: bool = False, force: bool = False) -> None:
    """Scaffold the full AI Coding infrastructure."""
    print(f"\n{'='*60}")
    print(f"  AI Coding Infrastructure Initialization")
    print(f"  Project: {project_name}")
    print(f"  Target:  {target_dir.resolve()}")
    if force:
        print(f"  Force:   ON (existing files will be overwritten)")
    print(f"{'='*60}\n")

    if dry_run:
        print("  DRY RUN — no files will be written\n")

    created = 0
    overwritten = 0
    skipped = 0

    for rel_path, template in FILE_MAP.items():
        full_path = target_dir / rel_path
        content = customize_content(template, project_name)
        written, existed = create_file(full_path, content, dry_run, force)
        if written:
            if existed:
                overwritten += 1
            else:
                created += 1
        else:
            skipped += 1

    print(f"\n{'='*60}")
    if dry_run:
        print(f"  Summary: {created} would create, {overwritten} would overwrite, {skipped} would skip")
    else:
        parts = []
        if created:
            parts.append(f"{created} created")
        if overwritten:
            parts.append(f"{overwritten} overwritten")
        if skipped:
            parts.append(f"{skipped} skipped")
        print(f"  Summary: {', '.join(parts)}")
    print(f"{'='*60}\n")

    # Copy the understand skill directory
    _copy_understand_skill(target_dir, dry_run, force)

    if not dry_run:
        _print_next_steps()
        _run_validation(target_dir)


def _copy_understand_skill(target_dir: Path, dry_run: bool = False, force: bool = False) -> None:
    """Copy the understand skill directory (agents-understand) into the target repo."""
    import shutil

    if not UNDERSTAND_SKILL_SOURCE.exists():
        return

    dest_skill = target_dir / "agents" / "skills" / "understand"
    dest_skill_dash = target_dir / "agents" / "skills" / "understand-dashboard"
    dest_scripts = target_dir / "scripts" / "understand"

    if dry_run:
        for d in [dest_skill, dest_scripts]:
            if d.exists() and not force:
                print(f"  ⚠  SKIP (exists): {d}")
            else:
                print(f"  ○  WOULD COPY: {d}")
        return

    # Copy understand skill
    _copy_dir(UNDERSTAND_SKILL_SOURCE / "skills" / "understand", dest_skill, force)
    _copy_dir(UNDERSTAND_SKILL_SOURCE / "skills" / "understand-dashboard", dest_skill_dash, force)

    # Copy understand scripts
    _copy_dir(UNDERSTAND_SKILL_SOURCE / "scripts" / "understand", dest_scripts, force)

    # Copy chromium_docs.py (standalone script in the skill's scripts/ dir)
    _copy_file(Path(__file__).parent / "chromium_docs.py", target_dir / "scripts" / "chromium_docs.py", force)

    # Copy references/ directory
    _copy_dir(Path(__file__).parent.parent / "references", target_dir / "agents" / "references", force)


def _copy_file(src: Path, dest: Path, force: bool) -> None:
    """Copy a single file, handling existing destinations."""
    import shutil
    if not src.exists():
        return
    if dest.exists():
        if force:
            dest.unlink()
            shutil.copy2(src, dest)
            print(f"  ✓  OVERWRITTEN: {dest}")
        else:
            print(f"  ⚠  SKIP (exists): {dest}")
    else:
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dest)
        print(f"  ✓  COPIED: {dest}")


def _copy_dir(src: Path, dest: Path, force: bool) -> None:
    """Copy a directory, handling existing destinations."""
    import shutil
    if not src.exists():
        return
    if dest.exists():
        if force:
            shutil.rmtree(dest)
            shutil.copytree(src, dest)
            print(f"  ✓  OVERWRITTEN: {dest}")
        else:
            print(f"  ⚠  SKIP (exists): {dest}")
    else:
        shutil.copytree(src, dest)
        print(f"  ✓  COPIED: {dest}")


