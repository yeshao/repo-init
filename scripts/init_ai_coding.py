def _run_validation(target_dir: Path) -> None:
    """Validate the scaffolded structure and warn about issues."""
    print("  Validation:")

    critical_files = [
        "agents/ai_policy.md",
        "agents/prompts/common.minimal.md",
        "agents/prompts/common.md",
        "agents/prompts/knowledge_base.md",
    ]

    important_files = [
        "agents/skills/understand/SKILL.md",
        "agents/skills/understand-dashboard/SKILL.md",
        "scripts/understand/scan_project.py",
        "scripts/understand/generate_context.py",
        "scripts/understand/build_graph.py",
        "scripts/understand/launch_dashboard.py",
        "scripts/chromium_docs.py",
    ]

    ok = True
    for rel in critical_files:
        path = target_dir / rel
        if path.exists():
            print(f"    ✓  {rel}")
        else:
            print(f"    ✗  MISSING: {rel}")
            ok = False

    # Check important (non-critical) files
    for rel in important_files:
        path = target_dir / rel
        if path.exists():
            print(f"    ✓  {rel}")
        else:
            print(f"    ⚠  MISSING: {rel}")

    # Warn about placeholder content
    example_skill = target_dir / "agents/skills/example-skill/SKILL.md"
    if example_skill.exists():
        content = example_skill.read_text(encoding="utf-8")
        if "example-skill" in content and "This is an example" in content:
            print(f"    ⚠  agents/skills/example-skill/SKILL.md is still a placeholder — replace or remove")

    if ok:
        print(f"\n    All critical files present. Ready for customization.\n")
    else:
        print(f"\n    Some critical files are missing. Re-run with --force to regenerate.\n")


def main():
    parser = argparse.ArgumentParser(
        description="Initialize a repository with AI Coding infrastructure"
    )
    parser.add_argument(
        "--dir",
        default=".",
        help="Target repository root directory (default: current directory)",
    )
    parser.add_argument(
        "--project-name",
        default="My Project",
        help="Name of the project (used in template placeholders)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Preview what would be created without writing files",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite existing files (default: skip existing)",
    )
    args = parser.parse_args()

    target = Path(args.dir)
    if not target.is_dir():
        print(f"Error: {target} is not a directory.", file=sys.stderr)
        sys.exit(1)

    init_repo(target, args.project_name, args.dry_run, args.force)


if __name__ == "__main__":
    main()
